using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using Pmad.CodeCondenser.Core.Configuration;
using Pmad.CodeCondenser.Core.Filtering;
using Pmad.CodeCondenser.Core.Models;
using Pmad.CodeCondenser.Core.Types;

namespace Pmad.CodeCondenser.Core.Lines;

/// <summary>
/// Detects methods and classes exceeding configured lines of code thresholds using Roslyn AST analysis.
/// </summary>
public sealed class LinesOfCodeDetector : ILinesOfCodeDetector
{
    /// <inheritdoc />
    public IReadOnlyList<LinesOfCodeViolation> DetectViolations(
        SyntaxTree syntaxTree,
        string relativePath,
        CodeCondenserSettings settings,
        FileCategory category = FileCategory.Production)
    {
        ArgumentNullException.ThrowIfNull(syntaxTree);
        ArgumentNullException.ThrowIfNull(settings);

        if (!settings.EnableLinesOfCodeDetection)
        {
            return [];
        }

        if (settings.ExcludeGeneratedCode &&
            (GeneratedCodeDetector.HasAutoGeneratedHeader(relativePath) ||
             GeneratedCodeDetector.HasAutoGeneratedHeaderInContent(syntaxTree.ToString())))
        {
            return [];
        }

        var normalizedPath = relativePath.Replace('\\', '/');
        var root = syntaxTree.GetRoot();
        var violations = new List<LinesOfCodeViolation>();

        // 1. Detect Class Violations
        foreach (var node in root.DescendantNodes())
        {
            if (node is ClassDeclarationSyntax classDecl)
            {
                CheckClassViolation(classDecl, classDecl.Identifier.Text, syntaxTree, normalizedPath, settings, category, violations);
            }
            else if (node is RecordDeclarationSyntax recordDecl && IsRecordClass(recordDecl))
            {
                CheckClassViolation(recordDecl, recordDecl.Identifier.Text, syntaxTree, normalizedPath, settings, category, violations);
            }
            else if (node is BaseMethodDeclarationSyntax methodDecl)
            {
                CheckMethodViolation(methodDecl, syntaxTree, normalizedPath, settings, category, violations);
            }
            else if (node is LocalFunctionStatementSyntax localFunc)
            {
                CheckLocalFunctionViolation(localFunc, syntaxTree, normalizedPath, settings, category, violations);
            }
            else if (node is AccessorDeclarationSyntax accessor)
            {
                CheckAccessorViolation(accessor, syntaxTree, normalizedPath, settings, category, violations);
            }
        }

        return violations;
    }

    private static bool IsRecordClass(RecordDeclarationSyntax recordDecl)
    {
        return !recordDecl.ClassOrStructKeyword.IsKind(SyntaxKind.StructKeyword);
    }

    private static void CheckClassViolation(
        TypeDeclarationSyntax typeDecl,
        string identifierName,
        SyntaxTree syntaxTree,
        string normalizedPath,
        CodeCondenserSettings settings,
        FileCategory category,
        List<LinesOfCodeViolation> violations)
    {
        if (GeneratedCodeDetector.HasGeneratedCodeAttribute(typeDecl) ||
            LinesOfCodeIgnoreMarker.IsIgnored(typeDecl))
        {
            return;
        }

        int loc = TypeLocCounter.CountLinesOfCode(typeDecl);
        if (loc > settings.ClassLinesOfCodeThreshold)
        {
            var lineSpan = syntaxTree.GetLineSpan(typeDecl.Span);
            var fullName = GetFullTypeIdentifier(typeDecl);

            violations.Add(new LinesOfCodeViolation
            {
                FilePath = normalizedPath,
                Identifier = fullName,
                Kind = LinesOfCodeKind.Class,
                LinesOfCode = loc,
                Threshold = settings.ClassLinesOfCodeThreshold,
                StartLine = lineSpan.StartLinePosition.Line + 1,
                EndLine = lineSpan.EndLinePosition.Line + 1,
                Category = category
            });
        }
    }

    private static void CheckMethodViolation(
        BaseMethodDeclarationSyntax methodDecl,
        SyntaxTree syntaxTree,
        string normalizedPath,
        CodeCondenserSettings settings,
        FileCategory category,
        List<LinesOfCodeViolation> violations)
    {
        if (GeneratedCodeDetector.HasGeneratedCodeAttribute(methodDecl) ||
            LinesOfCodeIgnoreMarker.IsIgnored(methodDecl))
        {
            return;
        }

        int loc = TypeLocCounter.CountLinesOfCode(methodDecl);
        if (loc > settings.MethodLinesOfCodeThreshold)
        {
            var lineSpan = syntaxTree.GetLineSpan(methodDecl.Span);
            var signature = GetMethodSignature(methodDecl);

            violations.Add(new LinesOfCodeViolation
            {
                FilePath = normalizedPath,
                Identifier = signature,
                Kind = LinesOfCodeKind.Method,
                LinesOfCode = loc,
                Threshold = settings.MethodLinesOfCodeThreshold,
                StartLine = lineSpan.StartLinePosition.Line + 1,
                EndLine = lineSpan.EndLinePosition.Line + 1,
                Category = category
            });
        }
    }

    private static void CheckLocalFunctionViolation(
        LocalFunctionStatementSyntax localFunc,
        SyntaxTree syntaxTree,
        string normalizedPath,
        CodeCondenserSettings settings,
        FileCategory category,
        List<LinesOfCodeViolation> violations)
    {
        if (GeneratedCodeDetector.HasGeneratedCodeAttribute(localFunc))
        {
            return;
        }

        int loc = TypeLocCounter.CountLinesOfCode(localFunc);
        if (loc > settings.MethodLinesOfCodeThreshold)
        {
            var lineSpan = syntaxTree.GetLineSpan(localFunc.Span);
            var enclosing = GetEnclosingMemberPrefix(localFunc);
            var signature = string.IsNullOrEmpty(enclosing)
                ? $"{localFunc.Identifier.Text}()"
                : $"{enclosing}.{localFunc.Identifier.Text}()";

            violations.Add(new LinesOfCodeViolation
            {
                FilePath = normalizedPath,
                Identifier = signature,
                Kind = LinesOfCodeKind.Method,
                LinesOfCode = loc,
                Threshold = settings.MethodLinesOfCodeThreshold,
                StartLine = lineSpan.StartLinePosition.Line + 1,
                EndLine = lineSpan.EndLinePosition.Line + 1,
                Category = category
            });
        }
    }

    private static void CheckAccessorViolation(
        AccessorDeclarationSyntax accessor,
        SyntaxTree syntaxTree,
        string normalizedPath,
        CodeCondenserSettings settings,
        FileCategory category,
        List<LinesOfCodeViolation> violations)
    {
        if (accessor.Body == null && accessor.ExpressionBody == null)
        {
            return;
        }

        if (GeneratedCodeDetector.HasGeneratedCodeAttribute(accessor))
        {
            return;
        }

        int loc = TypeLocCounter.CountLinesOfCode(accessor);
        if (loc > settings.MethodLinesOfCodeThreshold)
        {
            var lineSpan = syntaxTree.GetLineSpan(accessor.Span);
            var property = accessor.Parent?.Parent as PropertyDeclarationSyntax;
            var enclosing = property != null ? GetEnclosingTypePrefix(property) : string.Empty;
            var propName = property?.Identifier.Text ?? "Property";
            var accessorKind = accessor.Keyword.Text;
            var identifier = string.IsNullOrEmpty(enclosing)
                ? $"{propName}.{accessorKind}"
                : $"{enclosing}.{propName}.{accessorKind}";

            violations.Add(new LinesOfCodeViolation
            {
                FilePath = normalizedPath,
                Identifier = identifier,
                Kind = LinesOfCodeKind.Method,
                LinesOfCode = loc,
                Threshold = settings.MethodLinesOfCodeThreshold,
                StartLine = lineSpan.StartLinePosition.Line + 1,
                EndLine = lineSpan.EndLinePosition.Line + 1,
                Category = category
            });
        }
    }

    private static string GetFullTypeIdentifier(TypeDeclarationSyntax typeDecl)
    {
        var typePrefix = GetEnclosingTypePrefix(typeDecl);
        var name = typeDecl.Identifier.Text;
        return string.IsNullOrEmpty(typePrefix) ? name : $"{typePrefix}.{name}";
    }

    private static string GetMethodSignature(BaseMethodDeclarationSyntax method)
    {
        var typePrefix = GetEnclosingTypePrefix(method);
        var name = method switch
        {
            MethodDeclarationSyntax m => m.Identifier.Text,
            ConstructorDeclarationSyntax c => c.Identifier.Text,
            DestructorDeclarationSyntax d => $"~{d.Identifier.Text}",
            ConversionOperatorDeclarationSyntax conv => $"{conv.ImplicitOrExplicitKeyword.Text} operator {conv.Type}",
            OperatorDeclarationSyntax op => $"operator {op.OperatorToken.Text}",
            _ => "Method"
        };

        var parameters = method.ParameterList != null
            ? string.Join(", ", method.ParameterList.Parameters.Select(p => p.Type?.ToString() ?? p.Identifier.Text))
            : string.Empty;

        var fullMethod = $"{name}({parameters})";
        return string.IsNullOrEmpty(typePrefix) ? fullMethod : $"{typePrefix}.{fullMethod}";
    }

    private static string GetEnclosingTypePrefix(SyntaxNode node)
    {
        var enclosingTypes = new List<string>();
        var current = node.Parent;
        while (current != null)
        {
            if (current is TypeDeclarationSyntax typeDecl)
            {
                enclosingTypes.Add(typeDecl.Identifier.Text);
            }
            current = current.Parent;
        }
        enclosingTypes.Reverse();
        return string.Join(".", enclosingTypes);
    }

    private static string GetEnclosingMemberPrefix(SyntaxNode node)
    {
        var segments = new List<string>();
        var current = node.Parent;
        while (current != null)
        {
            if (current is MethodDeclarationSyntax m)
            {
                segments.Add(m.Identifier.Text);
            }
            else if (current is TypeDeclarationSyntax t)
            {
                segments.Add(t.Identifier.Text);
            }
            current = current.Parent;
        }
        segments.Reverse();
        return string.Join(".", segments);
    }
}
