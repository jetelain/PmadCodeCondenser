using FluentAssertions;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using Pmad.CodeCondenser.Core.Clones;
using Pmad.CodeCondenser.Core.Comments;
using Pmad.CodeCondenser.Core.Configuration;
using Pmad.CodeCondenser.Core.Filtering;

namespace Pmad.CodeCondenser.Core.Tests.Filtering;

public class GeneratedCodeDetectorTests : IDisposable
{
    private readonly string _tempDirectory;

    public GeneratedCodeDetectorTests()
    {
        _tempDirectory = Path.Combine(Path.GetTempPath(), "GenCodeDetectorTests_" + Guid.NewGuid().ToString("N"));
        Directory.CreateDirectory(_tempDirectory);
    }

    public void Dispose()
    {
        if (Directory.Exists(_tempDirectory))
        {
            Directory.Delete(_tempDirectory, recursive: true);
        }
    }

    [Fact]
    public void HasAutoGeneratedHeader_ReturnsTrue_WhenHeaderPresentInFirst20Lines()
    {
        var filePath = Path.Combine(_tempDirectory, "Generated.cs");
        File.WriteAllText(filePath, """
        // <auto-generated>
        //     This code was generated by a tool.
        // </auto-generated>
        namespace Test;
        public class MyGenClass {}
        """);

        GeneratedCodeDetector.HasAutoGeneratedHeader(filePath).Should().BeTrue();
    }

    [Fact]
    public void HasAutoGeneratedHeader_ReturnsTrue_WithXmlStyleTag()
    {
        var filePath = Path.Combine(_tempDirectory, "GeneratedXml.cs");
        File.WriteAllText(filePath, """
        //------------------------------------------------------------------------------
        // <autogenerated />
        //------------------------------------------------------------------------------
        namespace Test;
        public class MyGenClass {}
        """);

        GeneratedCodeDetector.HasAutoGeneratedHeader(filePath).Should().BeTrue();
    }

    [Fact]
    public void HasAutoGeneratedHeader_ReturnsFalse_WhenHeaderIsAfterLine20()
    {
        var filePath = Path.Combine(_tempDirectory, "NotGenerated.cs");
        var lines = Enumerable.Range(1, 25).Select(i => $"// Line {i}").ToList();
        lines.Add("// <auto-generated>");
        File.WriteAllLines(filePath, lines);

        GeneratedCodeDetector.HasAutoGeneratedHeader(filePath).Should().BeFalse();
    }

    [Fact]
    public void HasAutoGeneratedHeader_ReturnsFalse_WhenNoTagPresent()
    {
        var filePath = Path.Combine(_tempDirectory, "Manual.cs");
        File.WriteAllText(filePath, """
        // Regular manual file header
        namespace Test;
        public class MyManualClass {}
        """);

        GeneratedCodeDetector.HasAutoGeneratedHeader(filePath).Should().BeFalse();
    }

    [Fact]
    public void HasGeneratedCodeAttribute_ReturnsTrue_WhenAttributeOnMethod()
    {
        var code = """
        using System.CodeDom.Compiler;
        public class Sample
        {
            [GeneratedCode("Tool", "1.0")]
            public void GeneratedMethod() {}

            public void ManualMethod() {}
        }
        """;

        var tree = CSharpSyntaxTree.ParseText(code);
        var methods = tree.GetRoot().DescendantNodes().OfType<MethodDeclarationSyntax>().ToList();

        GeneratedCodeDetector.HasGeneratedCodeAttribute(methods[0]).Should().BeTrue();
        GeneratedCodeDetector.HasGeneratedCodeAttribute(methods[1]).Should().BeFalse();
    }

    [Fact]
    public void HasGeneratedCodeAttribute_ReturnsTrue_WhenAttributeOnEnclosingClass()
    {
        var code = """
        using System.CodeDom.Compiler;
        [GeneratedCode("EFCore", "9.0")]
        public class GeneratedContainer
        {
            public void InnerMethod() {}
        }
        """;

        var tree = CSharpSyntaxTree.ParseText(code);
        var method = tree.GetRoot().DescendantNodes().OfType<MethodDeclarationSyntax>().Single();

        GeneratedCodeDetector.HasGeneratedCodeAttribute(method).Should().BeTrue();
    }

    [Fact]
    public void HasGeneratedCodeAttribute_ReturnsTrue_WithCompilerGeneratedAttribute()
    {
        var code = """
        using System.Runtime.CompilerServices;
        public class Sample
        {
            [CompilerGenerated]
            public void HiddenCompilerMethod() {}
        }
        """;

        var tree = CSharpSyntaxTree.ParseText(code);
        var method = tree.GetRoot().DescendantNodes().OfType<MethodDeclarationSyntax>().Single();

        GeneratedCodeDetector.HasGeneratedCodeAttribute(method).Should().BeTrue();
    }

    [Fact]
    public void MethodExtractor_SkipsMethodsWithGeneratedCodeAttributeOrEnclosingType()
    {
        var code = """
        using System.CodeDom.Compiler;

        [GeneratedCode("Tool", "1.0")]
        public class AutoGenService
        {
            public void M1()
            {
                int a = 1; int b = 2; int c = 3; int d = 4;
                int e = 5; int f = 6; int g = 7; int h = 8;
            }
        }

        public class ManualService
        {
            [GeneratedCode("Tool", "1.0")]
            public void M2()
            {
                int a = 1; int b = 2; int c = 3; int d = 4;
                int e = 5; int f = 6; int g = 7; int h = 8;
            }

            public void M3()
            {
                int a = 1; int b = 2; int c = 3; int d = 4;
                int e = 5; int f = 6; int g = 7; int h = 8;
            }
        }
        """;

        var tree = CSharpSyntaxTree.ParseText(code);
        var extractor = new MethodExtractor(minStatements: 8);
        var methods = extractor.Extract(tree, minStatements: 8);

        // Only M3 should be extracted, M1 and M2 must be skipped due to GeneratedCode
        methods.Should().HaveCount(1);
        methods[0].Identifier.Text.Should().Be("M3");
    }

    [Fact]
    public void VerboseCommentExtractor_SkipsCommentsInGeneratedTypes()
    {
        var code = """
        using System.CodeDom.Compiler;

        [GeneratedCode("Tool", "1.0")]
        public class AutoGenService
        {
            // This is a verbose comment inside a generated class that should be skipped by the comment extractor
            public void M1() {}
        }

        public class ManualService
        {
            // This is a verbose comment inside a manual class that should be extracted because it is over the limit
            public void M2() {}
        }
        """;

        var tree = CSharpSyntaxTree.ParseText(code);
        var settings = new CodeCondenserSettings { CommentLengthThreshold = 50 };
        var extractor = new VerboseCommentExtractor();
        var comments = extractor.Extract(tree, "test.cs", settings);

        comments.Should().HaveCount(1);
        comments[0].OriginalText.Should().Contain("manual class");
    }

    [Fact]
    public void HasGeneratedCodeAttribute_ReturnsTrue_ForNodeInsideGeneratedMethod_InManualClass()
    {
        var code = """
        using System.CodeDom.Compiler;
        public class ManualService
        {
            [GeneratedCode("Tool", "1.0")]
            public void GeneratedMethod()
            {
                int x = 1;
            }
        }
        """;

        var tree = CSharpSyntaxTree.ParseText(code);
        var localDecl = tree.GetRoot().DescendantNodes().OfType<LocalDeclarationStatementSyntax>().Single();

        GeneratedCodeDetector.HasGeneratedCodeAttribute(localDecl).Should().BeTrue();
    }

    [Fact]
    public void VerboseCommentExtractor_SkipsCommentsInGeneratedMethod_InManualClass()
    {
        var code = """
        using System.CodeDom.Compiler;
        public class ManualService
        {
            [GeneratedCode("Tool", "1.0")]
            public void GeneratedMethod()
            {
                // This is a verbose comment inside a generated method that must be skipped by extractor
                int x = 1;
            }

            public void ManualMethod()
            {
                // This is a verbose comment inside a manual method that must be extracted by extractor
                int y = 2;
            }
        }
        """;

        var tree = CSharpSyntaxTree.ParseText(code);
        var settings = new CodeCondenserSettings { CommentLengthThreshold = 50 };
        var extractor = new VerboseCommentExtractor();
        var comments = extractor.Extract(tree, "test.cs", settings);

        comments.Should().HaveCount(1);
        comments[0].OriginalText.Should().Contain("manual method");
    }

    [Fact]
    public void VerboseCommentExtractor_ExtractsCommentsInGeneratedCode_WhenExcludeGeneratedCodeIsFalse()
    {
        var code = """
        using System.CodeDom.Compiler;
        [GeneratedCode("Tool", "1.0")]
        public class AutoGenService
        {
            // This is a verbose comment inside a generated class that should be extracted when ExcludeGeneratedCode is false
            public void M1() {}
        }
        """;

        var tree = CSharpSyntaxTree.ParseText(code);
        var settings = new CodeCondenserSettings
        {
            CommentLengthThreshold = 50,
            ExcludeGeneratedCode = false
        };
        var extractor = new VerboseCommentExtractor();
        var comments = extractor.Extract(tree, "test.cs", settings);

        comments.Should().HaveCount(1);
        comments[0].OriginalText.Should().Contain("generated class");
    }
}
